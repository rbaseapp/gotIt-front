export function LanguageFlag({ code }: { code: string }) {
  let locale: Intl.Locale;
  try {
    locale = new Intl.Locale(code);
  } catch {
    return null;
  }
  const country =
    locale.region && locale.region in flags
      ? (locale.region as keyof typeof flags)
      : regions[locale.language];
  const Flag = country ? flags[country] : undefined;
  return Flag ? <Flag className="pg-flag" aria-hidden="true" /> : null;
}
